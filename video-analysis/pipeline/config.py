# --- ④d·标注的稳定标识与失效校验（Task 46）---
# 事故背景：Book1 文化4组从 13 家变 14 家，新增那家排在第 8 位，其后企业
# 行号整体后移一位，而帧是按旧编号抽的、没重抽——seg 8-13 的衣着/颜色/
# 性别全部取自隔壁公司，整条流水线照常跑完、没有一处报错。修复要重抽帧 +
# 重检测，而重检测后 `track_id` 全部改变（它由 YOLO 跟踪器在检测时分配，
# 是跟踪器状态，不是稳定标识）。用户此前标注里的 `entry:19`/`exit:4` 因此
# 大部分指向不存在的 track（递补 5 人→0 人），少数碰巧编号还在、但那已经
# 是另一个人——错配不报错，会把别人的衣着编码成这个人的。用户明确说要标
# 60 多组，标识必须做稳。
#
# 稳定标识改由**视频内容**导出：`entryexit.stable_candidate_id(kind, t_mid,
# cx, y2)`。重检测后只会有像素级抖动，因此匹配**不能用字符串精确相等**，
# 用下面两个容差做模糊匹配（`entryexit.match_label_to_candidate`）。
#
# 时间容差 3.0 秒：进出场窗口按 TRANSITION_FPS=5 抽帧（每 0.2 秒一帧），
# 一条轨迹的 t 中位数会因重检测时首尾几帧的得失而漂移；3 秒 = 15 帧的漂移
# 余量，同时远小于 ENTRY_WINDOW/EXIT_WINDOW 的 40 秒跨度，不会把同一窗口
# 里前后两个不同的人混为一谈。
LABEL_MATCH_T_TOL = 3.0

# 位置容差 80.0 像素（(cx, y2) 的欧氏距离）：约为 1440px 画面宽度的 5.6%。
# 重检测的框位置抖动实际在十几像素量级；80px 留足余量，又明显小于相邻两
# 人的间距（本项目座位间距在 200px 以上），不会把隔壁那个人认成自己。
LABEL_MATCH_POS_TOL = 80.0

# 分级作废的匹配率下限：指纹不符时，若标注用的是稳定 id 格式，先尝试模糊
# 匹配并如实报告匹配数/丢弃数；匹配率低于本阈值才整份作废。0.7 的含义是
# 「三成以内的失配可以接受（人走动、候选被 TOP_N 截断都会造成个别失配），
# 超过三成说明这份标注根本不是这份检测的，宁可全废也不要错配」。旧格式
# （无 `_meta`）不走这条路径，一律整份作废——那正是会错配的情形。
LABEL_MATCH_MIN_RATE = 0.7


# 挑选页左侧「企业目录」固定栏的宽度（像素），与正文让出的 padding-left
# 由同一个数算出（`entryreview._TEMPLATE` 里的 __TOC_W__/__TOC_PAD__），
# 免得两处各写一个数、日后改了一处就把目录压在候选图上（用户 2026-08-21
# 要的就是「一点滑到对应的标记处」，目录盖住图等于白做）。
#
# 240px 的取法：一行要放得下「#12 某某（北京）科技有限公司」这一档长度的
# 企业名（14 家里最长的 13 个汉字，13px 字号约 170px）加上左侧图标与状态
# 边条；再宽就开始明显吃掉候选图的宽度——候选图占 .cand 的 62%，而这页
# 的全部价值在于让用户一眼认出候选是谁（Task 36 的教训：图不能压小）。
# 1440px 窗口下 240px 约占 17%，候选图仍有 500px 以上。
# 挑选页**没有**图片体积预算——图写成文件，页面只引用（用户 2026-09-18：
# 「HTML 引用原图，打开也快」，见 `entryreview._write_review_images`）。
#
# 这一条曾是 `ENTRY_REVIEW_MAX_MB = 32`，起因是用户 2026-09-08：「进入候选的
# 图像是蒙了一层纱……用原始的抽帧图」——城市1 那一版页面 183 张候选图里有
# **162 张**被降到 700px 重编码成 JPEG q85，只因整页超了画廊那份 12 MB 的
# 预算，而 `_fit_images_to_budget` 的返回值被丢掉，命令行与页面上都没有一个
# 字。「纱」本身是源帧的运动模糊，不是压出来的；但压缩确实让**人核对的图与
# 模型看到的图不是同一张**，这是本项目最忌讳的一类失效。
#
# 放宽到 32 MB 只是把它推远：一整组 264 张图原始 PNG 有 80 MB，照样要压。
# 写成文件之后降级路径整个消失——没有上限，也就没有「悄悄压一张」可言。
# 代价是页面不再自包含，转交他人标注要整个目录打包（页面上写着这句）。

