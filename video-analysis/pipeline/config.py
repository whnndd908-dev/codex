# --- 文件名净化（Task 33） ---
def sanitize_filename_component(name: str) -> str:
    """把任意字符串净化成可安全用作文件/目录名的片段。

    与 `pipeline.assemble.export_keyframes` 内企业名净化用的是**同一套
    规则**（挖掉 Windows/POSIX 都忌讳的 '/\\:*?"<>|'，再去首尾空白）——
    单一实现两处复用，不允许出现第二份从事同样事情但字符集稍有不同的代码
    （用户追加需求「result.csv 也要加组名」后，`run_all.py` 阶段 8/9 的产物
    文件名与画廊导出的人工校对版文件名都要净化 `config.SHEET`，
    `export_keyframes` 因此改为调用这里而不是自己另存一份同样的表达式）。
    净化后为空字符串（例如整个 sheet 名全是非法字符）时回退为 'unknown'，
    防止拼出 'result_.csv' 这种看不出是哪一组的文件名。
    """
    safe = "".join(c for c in name if c not in '/\\:*?"<>|').strip()
    return safe or "unknown"

